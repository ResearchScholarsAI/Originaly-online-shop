export function findSub(dept?: string, gender?: string, sub?: string) {
  const d = TAXONOMY.find((x) => x.id === dept);
  const g = d?.genders.find((x) => x.id === gender);
  const s = g?.subs.find((x) => x.id === sub);
  return { dept: d, gender: g, sub: s };
}

export function categoryPathFa(dept: string, gender: string, sub: string) {
  const f = findSub(dept, gender, sub);
  return [f.dept?.nameFa, f.gender?.nameFa, f.sub?.nameFa].filter(Boolean).join(" / ");
}
